//! Runtime traits and borrowed views for domain-object redaction.
//!
//! [`RedactionWriter`] provides scoped callbacks for structured values:
//! [`RedactionFields`] for record, tuple, and transparent values,
//! [`RedactionItems`] for sequences, and [`RedactionEntries`] for maps.
//! These scopes are supplied by the writer callback; ordinary callers should
//! not construct them directly.

#[doc(hidden)]
pub mod internal;
mod redact;
#[cfg(feature = "json")]
mod redact_json_value;
mod redact_level_value;
mod redact_map_key_value;
mod redact_map_value;
mod redaction_entries;
mod redaction_fields;
mod redaction_items;
mod redaction_writer;

#[cfg(any(feature = "serde", feature = "json"))]
pub use internal::RedactSerialize;
pub use redact::Redact;
#[cfg(feature = "json")]
pub use redact_json_value::RedactJsonValue;
pub use redact_level_value::RedactLevelValue;
pub use redact_map_key_value::RedactMapKeyValue;
pub use redact_map_value::RedactMapValue;
pub use redaction_entries::RedactionEntries;
pub use redaction_fields::RedactionFields;
pub use redaction_items::RedactionItems;
pub use redaction_writer::RedactionWriter;

mod redact_scalar;
/// Hidden support export used by code generated by the `Redact` derive macro.
///
/// This export is an internal support contract; it does not claim to make
/// manual downstream implementations impossible. Use [`RedactScalar`] to add
/// supported scalar values.
#[doc(hidden)]
pub use redact_level_value::private::Sealed as LevelValueSealed;
pub use redact_scalar::RedactScalar;
