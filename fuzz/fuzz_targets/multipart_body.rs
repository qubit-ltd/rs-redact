const FUZZ_SECRET: &str = "multipart-fuzz-secret-b08761d5";
const MAX_DIRECTED_CUTS: usize = 24;
const OUTPUT_BUDGETS: &[usize] = &[0, 1, 8, 9, 10, 16, 32, 64, 256];
const STRUCTURE_BUDGETS: &[usize] = &[0, 1, 2, 3, 4, 8, 16];
const DEPTH_BUDGETS: &[usize] = &[0, 1, 2, 3, 4, 8];

/// Encodes at most 2,048 arbitrary bytes as inert hexadecimal multipart text.
///
/// # Parameters
///
/// * `input` - Bytes to encode; bytes beyond the bounded prefix are ignored.
#[must_use]
#[cfg(not(test))]
fn encoded_noise(input: &[u8]) -> String {
    let mut encoded = String::with_capacity(input.len().saturating_mul(2));
    for byte in input.iter().take(2_048) {
        let _ = write!(encoded, "{byte:02x}");
    }
    encoded
}

/// Selects a deterministic cut anywhere from the empty prefix to the full body.
///
/// # Parameters
///
/// * `input` - Up to eight leading bytes interpreted as a zero-padded
///   little-endian word.
/// * `body_len` - Body length, bounded by the generated fuzz body sizes.
#[must_use]
#[inline]
fn random_cut(input: &[u8], body_len: usize) -> usize {
    let mut word = [0_u8; 8];
    let count = input.len().min(word.len());
    word[..count].copy_from_slice(&input[..count]);
    (u64::from_le_bytes(word) % (body_len as u64 + 1)) as usize
}

/// Selects one bounded budget deterministically, including for empty input.
///
/// `choices` must be nonempty; a missing input byte selects its first entry.
///
/// # Parameters
///
/// * `input` - Selector bytes; a missing byte selects the first choice.
/// * `index` - Offset of the selector byte.
/// * `choices` - Nonempty table of allowed budgets.
///
/// # Panics
///
/// Panics if `choices` is empty.
#[must_use]
#[inline]
fn selected_budget(input: &[u8], index: usize, choices: &[usize]) -> usize {
    choices[usize::from(input.get(index).copied().unwrap_or_default()) % choices.len()]
}

/// Creates an independent redactor with the selected output and traversal caps.
///
/// Input is capped at 65,536 bytes; invalid limit combinations panic rather
/// than silently weakening the fuzz case's requested limits.
///
/// # Parameters
///
/// * `output` - Maximum published byte count.
/// * `depth` - Maximum traversal depth.
/// * `nodes` - Maximum visited node count.
/// * `items` - Maximum visited collection item count.
///
/// # Panics
///
/// Panics if the policy builder rejects the supplied limits.
#[must_use]
#[cfg(not(test))]
fn budget_redactor(output: usize, depth: usize, nodes: usize, items: usize) -> Redactor {
    let policy = RedactionPolicy::builder()
        .limits(|limits| {
            limits
                .max_input_bytes(65_536)
                .max_output_bytes(output)
                .max_depth(depth)
                .max_nodes(nodes)
                .max_collection_items(items);
        })
        .expect("bounded limits are valid")
        .build()
        .expect("bounded policy is valid");
    Redactor::new(policy)
}

/// Builds a multipart fixture containing a secret and an inert public field.
///
/// `selector` cycles through JSON, form-encoded, and plain secret parts.
/// Callers supply a header-safe boundary and hex-encoded noise so neither can
/// inject additional multipart structure.
///
/// # Parameters
///
/// * `boundary` - Valid multipart boundary generated by the target.
/// * `noise` - Hexadecimal text safe to embed in JSON and form payloads.
/// * `selector` - Chooses JSON, URL-encoded form, or a password part modulo
///   three.
#[must_use]
#[cfg(not(test))]
fn selected_multipart_body(boundary: &str, noise: &str, selector: usize) -> String {
    let nested_part = match selector % 3 {
        0 => format!(
            "Content-Disposition: form-data; name=\"payload\"\r\nContent-Type: application/json\r\n\r\n{{\"password\":\"{FUZZ_SECRET}\",\"visible\":\"{noise}\"}}"
        ),
        1 => format!(
            "Content-Disposition: form-data; name=\"payload\"\r\nContent-Type: application/x-www-form-urlencoded\r\n\r\npassword={FUZZ_SECRET}&visible={noise}"
        ),
        _ => format!(
            "Content-Disposition: form-data; name=\"password\"\r\nContent-Type: text/plain\r\n\r\n{FUZZ_SECRET}"
        ),
    };
    format!(
        "--{boundary}\r\n{nested_part}\r\n--{boundary}\r\nContent-Disposition: form-data; name=\"public\"\r\n\r\nvisible-public\r\n--{boundary}--\r\n"
    )
}

/// Returns sorted, unique cuts around semantic multipart boundaries.
///
/// The result contains at most `MAX_DIRECTED_CUTS` byte offsets.
///
/// # Parameters
///
/// * `body` - Generated multipart body to inspect for fixture markers.
/// * `boundary` - Boundary used to locate password parts and the closing
///   marker.
#[must_use]
fn directed_cuts(body: &str, boundary: &str) -> Vec<usize> {
    let secret_start = body.find(FUZZ_SECRET);
    let upload_start = body.rfind(FUZZ_SECRET);
    let password_part = format!("--{boundary}\r\nContent-Disposition: form-data; name=\"password\"");
    let closing_marker = format!("--{boundary}--");
    let closing_start = body.rfind(&closing_marker);
    let anchors = [
        body.find(&password_part),
        secret_start,
        secret_start.map(|start| start + FUZZ_SECRET.len()),
        upload_start,
        upload_start.map(|start| start + FUZZ_SECRET.len()),
        closing_start,
        closing_start.map(|start| start + closing_marker.len()),
        Some(body.len()),
    ];
    let mut cuts = Vec::with_capacity(MAX_DIRECTED_CUTS);
    for anchor in anchors.into_iter().flatten() {
        for cut in [
            anchor.saturating_sub(1),
            anchor,
            anchor.saturating_add(1).min(body.len()),
        ] {
            cuts.push(cut);
        }
    }
    cuts.sort_unstable();
    cuts.dedup();
    cuts.truncate(MAX_DIRECTED_CUTS);
    cuts
}

/// Checks the publication invariants shared by every fuzzed operation.
///
/// # Parameters
///
/// * `output` - Redacted output whose published text is inspected.
/// * `max_output_bytes` - Maximum permitted published byte count.
///
/// # Panics
///
/// Panics if the text exceeds the budget or contains log-unsafe characters.
#[cfg(not(test))]
fn assert_output_invariants(output: &RedactionTextOutput, max_output_bytes: usize) {
    let text = output.text().as_str();
    assert!(text.len() <= max_output_bytes);
    log_safety::assert_log_safe(text);
}

#[cfg(not(test))]
fuzz_target!(|input: &[u8]| {
    let input = &input[..input.len().min(4_096)];
    let redactor = Redactor::standard();
    let max_output_bytes = redactor.policy().limits().max_output_bytes();
    let boundary = format!("qubit-fuzz-{}", encoded_noise(input.get(..16).unwrap_or(input)));
    let content_type = HeaderValue::from_str(&format!("multipart/form-data; boundary={boundary}"))
        .expect("hex-encoded boundary must be valid");

    let first = redactor.redact_http_body(BodyCapture::complete(input), Some(&content_type));
    let second = redactor.redact_http_body(BodyCapture::complete(input), Some(&content_type));
    assert_eq!(first, second);
    assert_output_invariants(&first, max_output_bytes);

    let noise = encoded_noise(input);
    let body = format!(
        "--{boundary}\r\n\
         Content-Disposition: form-data; name=\"note\"\r\n\r\n\
         {noise}\r\n\
         --{boundary}\r\n\
         Content-Disposition: form-data; name=\"password\"\r\n\r\n\
         {FUZZ_SECRET}\r\n\
         --{boundary}\r\n\
         Content-Disposition: form-data; name=\"upload\"; filename=\"secret.txt\"\r\n\
         X-Fuzz-Part: {noise}\r\n\
         Content-Type: application/octet-stream\r\n\r\n\
         {FUZZ_SECRET}\r\n\
         --{boundary}--\r\n"
    );
    let output = redactor.redact_http_body(BodyCapture::complete(body.as_bytes()), Some(&content_type));
    assert_output_invariants(&output, max_output_bytes);
    assert!(!output.text().as_str().contains(FUZZ_SECRET));

    let mut cuts = directed_cuts(&body, &boundary);
    cuts.push(random_cut(input, body.len()));
    cuts.sort_unstable();
    cuts.dedup();
    for retained in cuts {
        let capture = if retained == body.len() {
            BodyCapture::complete(body.as_bytes())
        } else {
            BodyCapture::prefix(body.as_bytes(), retained)
        };
        let output = redactor.redact_http_body(capture, Some(&content_type));
        assert_output_invariants(&output, max_output_bytes);
        assert!(!output.text().as_str().contains(FUZZ_SECRET));
        assert_eq!(
            output.summary().reasons().contains(RedactionReason::SourceTruncated),
            retained < body.len(),
        );
    }

    let output_budget = selected_budget(input, 17, OUTPUT_BUDGETS);
    let depth_budget = selected_budget(input, 18, DEPTH_BUDGETS);
    let node_budget = selected_budget(input, 19, STRUCTURE_BUDGETS);
    let item_budget = selected_budget(input, 20, STRUCTURE_BUDGETS);
    let budget_redactor = budget_redactor(output_budget, depth_budget, node_budget, item_budget);
    let combination = usize::from(input.get(21).copied().unwrap_or_default());
    let nested = selected_multipart_body(&boundary, &noise, combination);
    let selected_cut = random_cut(input.get(22..).unwrap_or_default(), nested.len());
    let capture = BodyCapture::prefix(nested.as_bytes(), selected_cut);
    let one_shot = budget_redactor.redact_http_body(capture, Some(&content_type));
    assert!(one_shot.summary().usage().output_bytes() <= output_budget);
    assert!(one_shot.summary().usage().visited_nodes() <= node_budget);
    assert!(one_shot.summary().usage().visited_collection_items() <= item_budget);
    assert!(one_shot.summary().usage().max_depth() <= depth_budget);
    assert_output_invariants(&one_shot, output_budget);
    assert!(!one_shot.text().as_str().contains(FUZZ_SECRET));
    // A restrictive budget may reject the body before source truncation is
    // recorded.

    let mut batch = budget_redactor.diagnostic_batch();
    let ordinary = batch.redact_field("ordinary", &noise);
    let multipart = batch.redact_http_body(capture, Some(&content_type));
    let batch_output = batch.finish_with_marker("<budget exhausted>");
    assert!(batch_output.summary().usage().output_bytes() <= output_budget);
    for handle in [ordinary, multipart] {
        let safe_text = batch_output.text(handle).as_str();
        assert!(!safe_text.contains(FUZZ_SECRET));
        log_safety::assert_log_safe(safe_text);
    }
});

#[cfg(test)]
mod tests {
    use super::DEPTH_BUDGETS;
    use super::OUTPUT_BUDGETS;
    use super::STRUCTURE_BUDGETS;
    use super::directed_cuts;
    use super::random_cut;
    use super::selected_budget;

    #[test]
    fn test_selected_budget_defaults_and_reaches_each_choice() {
        for choices in [OUTPUT_BUDGETS, STRUCTURE_BUDGETS, DEPTH_BUDGETS] {
            assert_eq!(selected_budget(&[], 0, choices), choices[0]);
            for (index, choice) in choices.iter().enumerate() {
                assert_eq!(selected_budget(&[index as u8], 0, choices), *choice);
            }
        }
        assert_eq!(selected_budget(&[0, 0, 7], 2, OUTPUT_BUDGETS), 64);
    }

    #[test]
    fn test_random_cut_uses_full_word_and_includes_body_end() {
        assert_eq!(random_cut(&1_024_u64.to_le_bytes(), 5_000), 1_024);
        assert_eq!(random_cut(&[], 5_000), 0);
        assert_eq!(random_cut(&5_000_u64.to_le_bytes(), 5_000), 5_000);
        assert!(
            random_cut(&u64::MAX.to_le_bytes(), 5_000) <= 5_000,
            "cut exceeds body length"
        );
    }

    #[test]
    fn test_directed_cuts_cover_semantic_boundaries_with_a_fixed_bound() {
        let boundary = "fuzz-boundary";
        let secret = "multipart-fuzz-secret-b08761d5";
        let body = format!(
            "--{boundary}\r\nContent-Disposition: form-data; name=\"note\"\r\n\r\n{}\r\n--{boundary}\r\nContent-Disposition: form-data; name=\"password\"\r\n\r\n{secret}\r\n--{boundary}\r\nContent-Disposition: form-data; name=\"upload\"; filename=\"secret.txt\"\r\nX-Fuzz-Part: noise\r\nContent-Type: application/octet-stream\r\n\r\n{secret}\r\n--{boundary}--\r\n",
            "x".repeat(300)
        );
        let cuts = directed_cuts(&body, boundary);
        assert!(cuts.len() <= 24, "directed cuts exceed the fixed bound");
        assert!(
            cuts.windows(2).all(|pair| pair[0] < pair[1]),
            "cuts must be sorted and unique"
        );
        assert!(cuts.iter().all(|cut| *cut <= body.len()), "cut exceeds body length");
        let password_part = "--fuzz-boundary\r\nContent-Disposition: form-data; name=\"password\"";
        let password_start = body.find(password_part).expect("password part in formatted body");
        assert!(
            cuts.iter().any(|cut| cut.abs_diff(password_start) <= 1),
            "missing password-part cut"
        );
        for marker in [secret, "--fuzz-boundary--"] {
            let start = body.find(marker).expect("marker in formatted body");
            let end = start + marker.len();
            assert!(
                cuts.iter().any(|cut| cut.abs_diff(start) <= 1),
                "missing start cut for {marker}"
            );
            assert!(
                cuts.iter().any(|cut| cut.abs_diff(end) <= 1),
                "missing end cut for {marker}"
            );
        }
        let upload_start = body.rfind(secret).expect("upload content in formatted body");
        let upload_end = upload_start + secret.len();
        assert!(
            cuts.iter().any(|cut| cut.abs_diff(upload_start) <= 1),
            "missing upload-start cut"
        );
        assert!(
            cuts.iter().any(|cut| cut.abs_diff(upload_end) <= 1),
            "missing upload-end cut"
        );
        assert!(
            cuts.iter().any(|cut| *cut > 255),
            "cuts must span beyond one byte's range"
        );
        assert!(cuts.contains(&body.len()), "missing complete-body cut");
    }
}
